def to_chinese_title(english_title: str) -> str | None:
    if not english_title:
        return None
    if english_title in CHINESE_TITLE_MAP:
        return CHINESE_TITLE_MAP[english_title]
    key = english_title.strip()
    if key in CHINESE_TITLE_MAP:
        return CHINESE_TITLE_MAP[key]
    if key.endswith(", The"):
        alt = "The " + key[:-5]
        if alt in CHINESE_TITLE_MAP:
            return CHINESE_TITLE_MAP[alt]
    if key.startswith("The "):
        alt = key[4:] + ", The"
        if alt in CHINESE_TITLE_MAP:
            return CHINESE_TITLE_MAP[alt]
    return None
